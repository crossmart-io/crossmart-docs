/**
 * Generates the nginx snippet for agent discovery from `src/data`, so the URLs live in one
 * place: the page `Link` header (RFC 8288). The API catalog itself is on crossmart.io. The Docker
 * image copies it to `/etc/nginx/snippets/`, where `deploy/nginx.conf.template` includes it.
 * Runs after `astro build`: `node scripts/build-nginx-snippets.ts`.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { SITE_URL } from '../src/data/site.ts';
import {
  AGENT_DISCOVERY_LINKS,
  formatLinkHeader,
  LinkMediaType,
  LinkRelation,
} from '../src/data/web-links.ts';

const OUTPUT_DIR = new URL('../build/nginx/', import.meta.url);
const HTTP_SNIPPET_FILE = 'agent-discovery.http.conf';

/** Set by `deploy/nginx.conf.template`: the page's `.md` path, empty for anything else. */
const PAGE_MARKDOWN_PATH_VARIABLE = '$page_markdown_path';
/** Set here, sent as the `Link` header of page responses. */
const PAGE_LINKS_VARIABLE = '$agent_discovery_links';

const GENERATED_NOTICE =
  '# Generated by scripts/build-nginx-snippets.ts from src/data. Do not edit.';

/** nginx strings are single-quoted here, so a value must not contain one. */
function quote(value: string): string {
  if (value.includes("'")) {
    throw new Error(`nginx value contains a single quote: ${value}`);
  }
  return `'${value}'`;
}

/** http level: maps a page's `.md` path to its full `Link` header; assets get none. */
function httpSnippet(): string {
  const pageLinks = formatLinkHeader([
    ...AGENT_DISCOVERY_LINKS,
    {
      href: `${SITE_URL}${PAGE_MARKDOWN_PATH_VARIABLE}`,
      rel: LinkRelation.Alternate,
      type: LinkMediaType.Markdown,
    },
  ]);
  return [
    GENERATED_NOTICE,
    `map ${PAGE_MARKDOWN_PATH_VARIABLE} ${PAGE_LINKS_VARIABLE} {`,
    `  "" "";`,
    `  default ${quote(pageLinks)};`,
    '}',
  ].join('\n');
}

async function buildNginxSnippets(): Promise<void> {
  await mkdir(OUTPUT_DIR, { recursive: true });
  await writeFile(new URL(HTTP_SNIPPET_FILE, OUTPUT_DIR), `${httpSnippet()}\n`);
  console.log(`nginx: wrote the snippet to ${fileURLToPath(OUTPUT_DIR)}`);
}

await buildNginxSnippets();
